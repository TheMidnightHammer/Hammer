HammerMesh::HammerMesh(HammerEngine& engine, HammerPipeline* pipeline, HammerTexture* texture, const std::vector<Vertex>& vertices, const std::vector<uint32_t>& indices) 
                       : engine(engine), pipeline(pipeline), texture(texture) {

    indexCount = static_cast<uint32_t>(indices.size());
    

    if (vertices.empty() || indices.size() == 0) {
        std::cerr << "HammerMesh Error: Cannot create mesh with 0 vertices/indices!" << std::endl;
        return; 
    }

    this->vertexData = vertices;
    this->indexData = indices;
    this->indexCount = static_cast<uint32_t>(indices.size());

    createVertexBuffer(vertices);
    createIndexBuffer(indices);
}

HammerMesh::~HammerMesh() {
    if (vertexBuffer != VK_NULL_HANDLE) {
        vkDestroyBuffer(engine.device, vertexBuffer, nullptr);
    }
    if (vertexBufferMemory != VK_NULL_HANDLE) {
        vkFreeMemory(engine.device, vertexBufferMemory, nullptr);
    }
    if (indexBuffer != VK_NULL_HANDLE) {
        vkDestroyBuffer(engine.device, indexBuffer, nullptr);
    }
    if (indexBufferMemory != VK_NULL_HANDLE) {
        vkFreeMemory(engine.device, indexBufferMemory, nullptr);
    }
}

void HammerMesh::createVertexBuffer(const std::vector<Vertex>& vertices) {
    if (vertices.empty()) return;

    VkDeviceSize bufferSize = sizeof(vertices[0]) * vertices.size();

    VkBuffer stagingBuffer;
    VkDeviceMemory stagingBufferMemory;

    engine.createBuffer(
        bufferSize, 
        VK_BUFFER_USAGE_TRANSFER_SRC_BIT, 
        VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT, 
        stagingBuffer, 
        stagingBufferMemory
    );

    void* data;
    vkMapMemory(engine.device, stagingBufferMemory, 0, bufferSize, 0, &data);
    memcpy(data, vertices.data(), (size_t)bufferSize);
    vkUnmapMemory(engine.device, stagingBufferMemory);

    engine.createBuffer(
        bufferSize, 
        VK_BUFFER_USAGE_TRANSFER_DST_BIT | VK_BUFFER_USAGE_VERTEX_BUFFER_BIT, 
        VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT, 
        vertexBuffer, 
        vertexBufferMemory
    );

    engine.copyBuffer(stagingBuffer, vertexBuffer, bufferSize);

    vkQueueWaitIdle(engine.graphicsQueue);

    vkDestroyBuffer(engine.device, stagingBuffer, nullptr);
    vkFreeMemory(engine.device, stagingBufferMemory, nullptr);
}

